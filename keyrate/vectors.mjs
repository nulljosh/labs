// Writes vectors.json from score.js, then the Kotlin and Swift tests that must agree with it.
// Run `node vectors.mjs` after changing score.js or the cases; vectors.test.mjs fails if anything is stale.
import { writeFileSync } from 'node:fs'
import { stats } from './score.js'

const w = s => (s === '' ? [] : s.split(' '))
// [typed, target, seconds]: perfect runs, typos, extra and missing letters, empty words, rounding edges
export const CASES = [
  ['the quick brown fox jumps', 'the quick brown fox jumps', 60],
  ['teh cat', 'the cat', 30],
  ['', '', 0],
  ['catss', 'cat', 60],
  ['ca', 'cat', 60],
  ['a', 'a', 60],
  ['a b', 'a b', 1],
  ['the be of', 'the be of', 2.5],
  ['the be of', 'the be or', 2.5],
  ['x', 'the', 60],
  ['the', 'the be of and', 15],
  ['the be of and', 'the', 15],
  ['the  be', 'the of be', 10],
  ['abcdefghijklmnop', 'abc', 60],
  ['hello world', 'hello world', 0.001],
  ['hello world', 'hello world', 0.0004],
  ['Hello world', 'hello world', 12],
  ['hello, world.', 'hello, world.', 12],
  ['hello world', 'hello, world.', 12],
  ['123 456', '123 456', 7],
  ['one two three four five six seven eight nine ten', 'one two three four five six seven eight nine ten', 30],
  ['one two thre four five six seven eight nine ten', 'one two three four five six seven eight nine ten', 30],
  ['one two three', 'one two three four five six seven eight nine ten', 60],
  ['aaaa bbbb', 'aaab bbba', 45],
  ['the', 'the', 0.06],
  ['the the the the the', 'the the the the the', 59.9],
  ['quick', 'quack', 4],
  ['qu', 'quick', 4],
  ['quickly', 'quick', 4],
  ['a b c d e f g h i j', 'a b c d e f g h i j', 6],
]

const vectors = CASES.map(([typed, target, seconds]) => ({ typed: w(typed), target: w(target), seconds, expect: stats(w(typed), w(target), seconds) }))


const kl = a => `listOf(${a.map(s => JSON.stringify(s)).join(', ')})`
const num = n => (Number.isInteger(n) ? n.toFixed(1) : String(n))
export function kotlin() {
  return `package com.nulljosh.keyrate

import kotlin.test.Test
import kotlin.test.assertEquals

// Generated by vectors.mjs from score.js. Do not edit; run \`node vectors.mjs\`.
class VectorsTest {
    @Test fun agreesWithScoreJs() {
${vectors.map(({ typed, target, seconds, expect: e }) => `        assertEquals(Stats(${e.wpm}, ${e.raw}, ${e.accuracy}, ${e.correct}, ${e.wrong}, ${e.correctWords}), stats(${kl(typed)}, ${kl(target)}, ${num(seconds)}))`).join('\n')}
    }
}
`
}

const sl = a => `[${a.map(s => JSON.stringify(s)).join(', ')}]`
export function swift() {
  return `import XCTest

// Generated by vectors.mjs from score.js. Do not edit; run \`node vectors.mjs\`.
final class VectorsTests: XCTestCase {
    private func check(_ typed: [String], _ target: [String], _ seconds: Double, _ want: [Int], line: UInt = #line) {
        let s = stats(typed: typed, target: target, seconds: seconds)
        XCTAssertEqual([s.wpm, s.raw, s.accuracy, s.correct, s.wrong, s.correctWords], want, line: line)
    }

    func testAgreesWithScoreJs() {
${vectors.map(({ typed, target, seconds, expect: e }) => `        check(${sl(typed)}, ${sl(target)}, ${num(seconds)}, [${e.wpm}, ${e.raw}, ${e.accuracy}, ${e.correct}, ${e.wrong}, ${e.correctWords}])`).join('\n')}
    }
}
`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL('./vectors.json', import.meta.url), JSON.stringify(vectors, null, 1) + '\n')
  writeFileSync(new URL('./kmp/shared/src/commonTest/kotlin/com/nulljosh/keyrate/VectorsTest.kt', import.meta.url), kotlin())
  writeFileSync(new URL('./apple/KeyrateTests/VectorsTests.swift', import.meta.url), swift())
  console.log(`${vectors.length} vectors written`)
}
