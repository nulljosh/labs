// Writes the Swift and Kotlin copies of the word list and quotes from words.js, the one source.
// Run `node wordlist.mjs` after editing words.js; wordlist.test.mjs fails if a copy is stale.
import { writeFileSync } from 'node:fs'
import { WORDS, QUOTES } from './words.js'

const wrap = (ws, width = 100) => ws.reduce((lines, w) => {
  const last = lines.at(-1)
  if (last && (last + ' ' + w).length <= width) lines[lines.length - 1] = last + ' ' + w; else lines.push(w)
  return lines
}, []).join('\n')
const q = s => JSON.stringify(s)

export function swift() {
  return `// Generated by wordlist.mjs from words.js. Do not edit; run \`node wordlist.mjs\`.

let words: [String] = """
${wrap(WORDS)}
""".split(whereSeparator: \\.isWhitespace).map(String.init)

let quotes: [String] = [
${QUOTES.map(s => `    ${q(s)},`).join('\n')}
]
`
}

export function kotlin() {
  return `package com.nulljosh.keyrate

// Generated by wordlist.mjs from words.js. Do not edit; run \`node wordlist.mjs\`.

val WORDS: List<String> = """
${wrap(WORDS)}
""".trim().split(Regex("\\\\s+"))

val QUOTES: List<String> = listOf(
${QUOTES.map(s => `    ${q(s)},`).join('\n')}
)
`
}

export const SWIFT = new URL('./apple/Keyrate/Words.swift', import.meta.url)
export const KOTLIN = new URL('./kmp/shared/src/commonMain/kotlin/com/nulljosh/keyrate/Words.kt', import.meta.url)

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(SWIFT, swift())
  writeFileSync(KOTLIN, kotlin())
  console.log(`${WORDS.length} words, ${QUOTES.length} quotes written`)
}
