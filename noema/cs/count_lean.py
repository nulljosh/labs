"""Write the Lean files that machine-check A004147(3) and A386859(3) by the tree (proofs/FarCerts/Count3*.lean).

    python3 count_lean.py

The kernel needs about 80 KB per simulated step, so one check of the whole 3-state tree (1.1 million steps) runs
out of memory. This splits it: every subtree of at most T steps is checked on its own, and the top of the tree
reads those values, in tree order, from one stored list. Uses the same encoding as CountTree.lean.
"""
import sys

N, B, T = 3, 20, 8000
b = 4 * N + 4
sys.setrecursionlimit(10000)


def run(p, k, q, L, a, R):
    """Run until an undefined entry or past B; returns (k, steps, config) or None."""
    steps = 0
    while True:
        if k > B:
            return None, steps
        e = 2 * q + a
        if p[e] is None:
            return (k, q, L, a, R), steps
        x = p[e] - 4
        w, mv, nx = x % 2, x // 2 % 2, x // 4
        if mv:
            L, a, R = [w] + L, (R[0] if R else 0), R[1:]
        else:
            R, a, L = [w] + R, (L[0] if L else 0), L[1:]
        q, k, steps = nx, k + 1, steps + 1


def walk(p, k, q, L, a, R):
    """(count, step sum, steps simulated) over every completion of p."""
    st, steps = run(p, k, q, L, a, R)
    if st is None:
        return 0, 0, steps
    k, q, L, a, R = st
    e, u = 2 * q + a, p.count(None)
    cnt, ssum = 4 * b ** (u - 1), 4 * b ** (u - 1) * (k + 1)
    for x in range(4, b):
        p2 = list(p); p2[e] = x
        c, s, t = walk(p2, k, q, L, a, R)
        cnt, ssum, steps = cnt + c, ssum + s, steps + t
    return cnt, ssum, steps


def frontier(p, k, q, L, a, R, out):
    """Collect the nodes small enough to check alone; expand the rest."""
    cnt, ssum, steps = walk(p, k, q, L, a, R)
    if steps <= T and p != [None] * (2 * N):
        out.append((p, k, (q, L, a, R), cnt, ssum))
        return
    st, _ = run(p, k, q, L, a, R)
    if st is None:
        return
    k, q, L, a, R = st
    for x in range(4, b):
        p2 = list(p); p2[2 * q + a] = x
        frontier(p2, k, q, L, a, R, out)


def lp(p):
    return '[' + ', '.join('none' if x is None else f'some {x}' for x in p) + ']'


def lc(c):
    q, L, a, R = c
    return f'⟨{q}, {L}, {a}, {R}⟩'


def main():
    nodes = []
    frontier([None] * (2 * N), 0, 0, [], 0, [], nodes)
    assert walk([None] * (2 * N), 0, 0, [], 0, [])[:2] == (7571840, 13141792)
    steps = [walk(n[0], n[1], *n[2])[2] for n in nodes]
    groups = []  # consecutive runs in tree order, each at most T steps, so the pieces read back as one stream
    for i in range(len(nodes)):
        if groups and groups[-1][0] + steps[i] <= T:
            groups[-1][0] += steps[i]; groups[-1][1].append(i)
        else:
            groups.append([steps[i], [i]])
    head = 'import FarCerts.CountTree\n\nset_option maxRecDepth 100000\n\nnamespace FAR\nnamespace Count\n\n'
    head += '-- generated by count_lean.py: pieces of the 3-state tree, each checked alone\n'
    files, cur, names = {}, '', []
    for j, (_, ix) in enumerate(groups):
        ents = ',\n  '.join(f'({lp(nodes[i][0])}, {nodes[i][1]}, {lc(nodes[i][2])}, {nodes[i][3]}, {nodes[i][4]})' for i in ix)
        cur += (f'def g{j} : List (List (Option Nat) × Nat × Config × Nat × Nat) := [\n  {ents}]\n'
                f'theorem g{j}_ok : chk 16 20 7 (fun _ => 1) id g{j} = true := by decide +kernel\n\n')
        names.append(f'g{j}')
        if len(cur) > 14000 or j == len(groups) - 1:
            files[f'Count3G{len(files)}.lean'] = head + cur + 'end Count\nend FAR\n'
            cur = ''
    imports = ''.join(f'import FarCerts.{fn[:-5]}\n' for fn in files)
    chain = 'fun _ h => nomatch h'
    for nm in reversed(names):
        chain = f'List.forall_mem_cons.2 ⟨{nm}_ok, {chain}⟩'
    files['Count3Pieces.lean'] = (imports + '\nset_option maxRecDepth 100000\n\nnamespace FAR\nnamespace Count\n\n'
        '-- generated by count_lean.py\ndef pieces3 : List (List (Option Nat) × Nat × Config × Nat × Nat) :=\n  List.flatten ['
        + ', '.join(names) + ']\n\ntheorem pieces3_ok : chk 16 20 7 (fun _ => 1) id pieces3 = true :=\n  chk_flatten _ _ _ _ _ _ ('
        + chain + ')\n\nend Count\nend FAR\n')
    for fn, txt in files.items():
        open(f'proofs/FarCerts/{fn}', 'w').write(txt)
    print(len(nodes), 'subtrees in', len(groups), 'pieces,', max(g[0] for g in groups), 'steps at most,', len(files), 'files')


if __name__ == '__main__':
    main()
