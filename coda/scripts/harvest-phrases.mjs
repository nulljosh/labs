// v56 harvest: everyday words and phrases that came from a book, play, film or show, with the
// meaning Wordroot gives (Wiktionary, CC BY-SA). Origins are the well-documented ones; a hint picks the
// sense the work gave us (gaslight the verb, not the lamp). A word whose meaning Wordroot can't find
// is dropped. Writes phrases-data.js, loaded before phrases.js.
import fs from 'fs';
const WORDS = [
  ['gaslight', /manipulat/, 'Gaslight', 'film', 1944], ['Catch-22', /dilemma|paradox|no-win|contradictory|situation|impossib/, 'Catch-22', 'novel', 1961], ['Big Brother', /surveil|government|authorit|watch/, 'Nineteen Eighty-Four', 'novel', 1949],
  ['doublethink', 'Nineteen Eighty-Four', 'novel', 1949], ['robot', /machine|mechanical|automat/, 'R.U.R.', 'play', 1920], ['muggle', /magic|wizard/, 'Harry Potter and the Philosopher’s Stone', 'novel', 1997],
  ['jump the shark', 'Happy Days', 'TV series', 1977], ['nerd', 'If I Ran the Zoo', 'book', 1950], ['grinch', 'How the Grinch Stole Christmas!', 'book', 1957],
  ['scrooge', 'A Christmas Carol', 'novella', 1843], ['chortle', 'Through the Looking-Glass', 'novel', 1871], ['galumph', 'Through the Looking-Glass', 'novel', 1871],
  ['Pollyanna', /optimis|cheerful|positive/, 'Pollyanna', 'novel', 1913], ['quixotic', 'Don Quixote', 'novel', 1605], ['malapropism', 'The Rivals', 'play', 1775],
  ['Shangri-La', 'Lost Horizon', 'novel', 1933], ['Svengali', /./, 'Trilby', 'novel', 1894], ['meme', 'The Selfish Gene', 'book', 1976],
  ['Lilliputian', 'Gulliver’s Travels', 'novel', 1726], ['yahoo', 'Gulliver’s Travels', 'novel', 1726], ['pandemonium', 'Paradise Lost', 'poem', 1667],
  ['utopia', /./, 'Utopia', 'book', 1516], ['red pill', 'The Matrix', 'film', 1999], ['paparazzo', /photograph/, 'La Dolce Vita', 'film', 1960],
  ['Stepford wife', 'The Stepford Wives', 'novel', 1972], ['Walter Mitty', 'The Secret Life of Walter Mitty', 'short story', 1939], ['D’oh', 'The Simpsons', 'TV series', 1989],
];
const out = [];
for (const row of WORDS) {
  const hint = row[1] instanceof RegExp ? row.splice(1, 1)[0] : /./;
  const [word, work, kind, year] = row;
  // Original capitals first (Catch-22, Shangri-La), then lower case; the sense the work gave us, by hint.
  let d = null, meaning = null;
  for (const form of [...new Set([word, word.toLowerCase()])]) {
    const r = await fetch(`https://wordroot.jaybulb.com/api/definitions/${encodeURIComponent(form.replace('’', "'"))}`).catch(() => null);
    d = r?.ok ? await r.json() : null;
    meaning = d?.definitions?.flatMap(p => p.definitions).find(m => !/alternative (letter-case )?form|plural of|misspelling|taken as a group/i.test(m) && hint.test(m));
    if (meaning) break;
  }
  if (!meaning) { console.log('no meaning:', word); continue; }
  meaning = meaning.replace(/\s*\(.*?\)\s*$/, '').replace(/\.$/, '');
  out.push({ word, work, kind, year, meaning, source: d.source });
  console.log(`${word} | ${work} | ${meaning.slice(0, 80)}`);
  await new Promise(r => setTimeout(r, 300));
}
fs.writeFileSync(new URL('../phrases-data.js', import.meta.url),
  `// Generated by scripts/harvest-phrases.mjs. Meanings from Wordroot (Wiktionary, CC BY-SA 4.0).\n(function (root) {\n  const PHRASES = ${JSON.stringify(out, null, 1)};\n  if (typeof module !== 'undefined') module.exports = PHRASES; else root.PHRASES = PHRASES;\n})(this);\n`);
console.log(WORDS.length, 'words', out.length, 'with a meaning');
