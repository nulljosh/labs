// Builds cities/<code>.js (web) and apple/Shared/cities-<code>.json (native): every city the search knows, named
// in each language. Time zone cities come from CLDR (the names browsers and Apple use), the aliases (Mumbai,
// Boston...) from Wikidata. Only names that differ from English are written. Needs the network. Run after changing ALIASES: node scripts/gen_cities.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import vm from 'node:vm';
const root = new URL('..', import.meta.url).pathname;
const LANGS = ['fr', 'es', 'de', 'ja', 'zh', 'pt', 'ko', 'it', 'nl', 'ar', 'hi'];
const WIKI = { zh: 'zh-hans', pt: 'pt-br' };   // Wikidata codes for Simplified Chinese and Brazilian Portuguese
// English Wikipedia titles where the alias alone is ambiguous or a redirect.
const TITLE = { 'Washington DC': 'Washington, D.C.', 'Portland': 'Portland, Oregon', 'Austin': 'Austin, Texas', 'Bangalore': 'Bengaluru', 'Delhi': 'Delhi', 'Frankfurt': 'Frankfurt', 'Manchester': 'Manchester' };

const ctx = {}; vm.runInNewContext(readFileSync(root + 'lib.js', 'utf8') + ';this.ALIASES = ALIASES;', ctx);
// The same map world.js builds: aliases first, then the last part of every zone id.
const cities = new Map(Object.entries(ctx.ALIASES));
Intl.supportedValuesOf('timeZone').forEach(z => { if (z.includes('/') && !z.startsWith('Etc/')) cities.set(z.split('/').pop().replaceAll('_', ' '), z); });
const fromZone = (city, zone) => zone.split('/').pop().replaceAll('_', ' ') === city;

const aliases = [...cities].filter(([c, z]) => !fromZone(c, z)).map(([c]) => c);
const wiki = {};
const q = new URLSearchParams({ action: 'wbgetentities', sites: 'enwiki', titles: aliases.map(c => TITLE[c] || c).join('|'), props: 'labels|sitelinks', sitefilter: 'enwiki', languages: LANGS.map(l => WIKI[l] || l).join('|'), format: 'json' });
const res = await (await fetch('https://www.wikidata.org/w/api.php?' + q, { headers: { 'User-Agent': 'horula-gen/1.0 (https://horula.jaybulb.com)' } })).json();
for (const e of Object.values(res.entities)) {
  const title = e.sitelinks?.enwiki?.title, city = aliases.find(c => (TITLE[c] || c) === title);
  if (city) wiki[city] = e.labels;
}

mkdirSync(root + 'cities', { recursive: true });
for (const l of LANGS) {
  const cldr = await (await fetch(`https://cdn.jsdelivr.net/npm/cldr-dates-full@46.0.0/main/${l}/timeZoneNames.json`)).json();
  const tree = cldr.main[l].dates.timeZoneNames.zone, names = {};
  for (const [city, zone] of cities) {
    const name = fromZone(city, zone)
      ? zone.split('/').reduce((n, part) => n?.[part], tree)?.exemplarCity
      : wiki[city]?.[WIKI[l] || l]?.value.split(/[,،]/)[0].trim();   // "Portland, Oregon" reads "Portland"
    if (name && name !== city) names[city] = name;
  }
  const sorted = Object.fromEntries(Object.entries(names).sort(([a], [b]) => a.localeCompare(b)));
  writeFileSync(`${root}apple/Shared/cities-${l}.json`, JSON.stringify(sorted) + '\n');   // the same names for the native app
  writeFileSync(`${root}cities/${l}.js`, `// Generated by scripts/gen_cities.mjs: city names in ${l}, from CLDR and Wikidata. Do not edit.\n(self.CITY_TEXT ||= {}).${l} = ${JSON.stringify(sorted)};\n`);
  console.log(l, Object.keys(sorted).length, 'of', cities.size, wiki.Mumbai?.[WIKI[l] || l] ? '' : '(no Wikidata labels)');
}
