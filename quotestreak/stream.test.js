const assert = require('assert');
const { parse, vote, tally } = require('./stream');
assert.deepEqual(parse('@badge-info=;color=#FF0000 :Sam!sam@sam.tmi.twitch.tv PRIVMSG #chan :2'), { user: 'sam', text: '2' });
assert.deepEqual(parse(':ann!ann@ann.tmi.twitch.tv PRIVMSG #chan :the godfather'), { user: 'ann', text: 'the godfather' });
assert.equal(parse('PING :tmi.twitch.tv'), null);
assert.equal(parse(':tmi.twitch.tv 001 justinfan123 :Welcome, GLHF!'), null);
const opts = ['Jaws', 'The Godfather', 'Alien', 'Amélie'];
assert.equal(vote('1', opts), 0);
assert.equal(vote('4', opts), 3);
assert.equal(vote('5', opts), -1);
assert.equal(vote('godfather', opts), 1);
assert.equal(vote('AMELIE!', opts), 3);
assert.equal(vote('lol', opts), -1);
const votes = new Map([['a', 1], ['b', 1], ['c', 0]]);
assert.deepEqual(tally(votes, opts, 'The Godfather'), { counts: [1, 2, 0, 0], total: 3, won: true });
assert.equal(tally(votes, opts, 'Jaws').won, false);
assert.equal(tally(new Map([['a', 0], ['b', 1]]), opts, 'Jaws').won, false, 'a tie is not a win');
assert.equal(tally(new Map(), opts, 'Jaws').won, false);
console.log('stream ok');
