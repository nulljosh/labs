const assert = require('assert');
const { next, state, points, key, COUNT, ASK, STEP } = require('./show');
const sunday = Date.UTC(2026, 9, 25, 18);   // Sunday 25 October 2026, 18:00 UTC
assert.strictEqual(next(Date.UTC(2026, 9, 19, 12)), sunday, 'Monday points to Sunday');
assert.strictEqual(next(sunday - 1000), sunday);
assert.strictEqual(next(sunday + 60000), sunday, 'a show in progress is the show');
assert.strictEqual(next(sunday + COUNT * STEP), sunday + 7 * 86400000, 'after it ends, next week');
assert.strictEqual(next(Date.UTC(2026, 9, 25, 20)), sunday + 7 * 86400000, 'Sunday evening points a week on');
assert.strictEqual(state(sunday, sunday - 5000).phase, 'waiting');
assert.deepStrictEqual(state(sunday, sunday + 1000), { phase: 'ask', i: 0, ms: ASK - 1000 });
assert.strictEqual(state(sunday, sunday + ASK + 1).phase, 'reveal');
assert.strictEqual(state(sunday, sunday + STEP + 1).i, 1, 'a late joiner lands on the live question');
assert.strictEqual(state(sunday, sunday + COUNT * STEP).phase, 'over');
assert.strictEqual(points(ASK), 20);
assert.strictEqual(points(0), 10);
assert.strictEqual(key(sunday), '2026-10-25');
const Daily = require('./daily');
const bank = require('./quotes.json');
const a = require('./show').pick('2026-10-25', bank, Daily.seededShuffle), b = require('./show').pick('2026-10-25', bank, Daily.seededShuffle);
assert.strictEqual(a.length, COUNT);
assert.deepStrictEqual(a.map(q => q.quote), b.map(q => q.quote), 'same twelve in every browser');
assert.strictEqual(new Set(a.map(q => q.quote)).size, COUNT);
console.log('show ok');
